import pandas as pd
import matplotlib.pyplot as plt
df=pd.read_csv("sales_data.csv")
print(df.head())
df.info()
print(df.describe())
print(df.isnull().sum())
print(df[df["City"].isnull()])
#replacing Nan in city with unknown 
df["City"]=df["City"].fillna("unknown")
print(df["City"].isnull().sum())
print(df["Unit_Price"].isnull().sum())
df["Unit_Price"]=df["Unit_Price"].fillna(df["Sales"]/df["Quantity"])
print(df["Unit_Price"].isnull().sum())
print(df.isnull().sum())
print(df[df["Payment_Method"].isnull()])
df["Payment_Method"]=df["Payment_Method"].fillna("unknown")
print(df.isnull().sum())
print("City with Highest Sales:")
print(df.groupby("City")["Sales"].sum().idxmax())
print("Total revenues generated:")
print(df["Sales"].sum())
print("Average sales per order:")
print(df["Sales"].mean())
print("Category that produces highest total sales")
category_sales=df.groupby("Category")["Sales"].sum()
print(f"{category_sales.idxmax()}:{category_sales.max()}")
category_sales.plot(kind="bar")
plt.title("Sales by Category")
plt.xlabel("Category")
plt.ylabel("Total sales")
plt.show()
print("Product that has been ordered more frequently")
print(df.groupby("Product")["Quantity"].sum().idxmax())
print(df.groupby("Product")["Quantity"].sum().max())
print(df["Product"].value_counts())
print("Payment method preferred by the customers")
print(df["Payment_Method"].value_counts().idxmax())
print(df["Order_Date"].dtype)
df["Order_Date"]=pd.to_datetime(df["Order_Date"])
print(df["Order_Date"].dtype)
city_sales=df.groupby("City")["Sales"].sum()
city_sales.plot(kind="bar")
plt.title("Sales by cities")
plt.xlabel("City")
plt.ylabel("Sales")
plt.show()
df["Month"]=df["Order_Date"].dt.month
monthly_sales=df.groupby("Month")["Sales"].sum()
monthly_sales.plot(kind="line")
plt.title("Monthly_sales")
plt.xlabel("Months")
plt.ylabel("Sales")
plt.show()
print("Business Insights")
print("1. Electronics generated the highest total sales.")
print("2. Hyderabad had the highest total sales among the cities.")
print("3. Headphones had the highest total quantity sold.")
print("4. Credit Card was the most frequently used payment method.")